#!/usr/bin/env node
/*
 * Writes the HTML shell of every screen from assets/registry.js. A screen file holds only the frame: the renderer for
 * its ID in assets/mtr-*.js draws the content. Run after adding a screen to the registry: node tools/build.js
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
global.window = {};
eval(fs.readFileSync(path.join(root, 'assets/registry.js'), 'utf8'));
const P = window.PORTAL;
const MODULES = ['mtr-auth', 'mtr-overview', 'mtr-processing', 'mtr-mapping', 'mtr-bc', 'mtr-cancel', 'mtr-admin'];
let n = 0;
P.portals.forEach(p => {
  p.screens.forEach(s => {
    const app = p.id !== 'authentication';
    const html = `<!doctype html>
<html lang="en">
<!-- Generated by tools/build.js from assets/registry.js: the content is drawn by the renderer for ${s.id} in assets/mtr-*.js. -->
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${s.name} (${s.id})</title>
<link rel="stylesheet" href="../../assets/fonts.css">
<link rel="stylesheet" href="../../assets/styles.css">
${app ? '<link rel="stylesheet" href="../../assets/app.css">\n' : ''}<link rel="stylesheet" href="../../assets/behaviour.css">
<link rel="stylesheet" href="../../assets/mtr.css">
</head>
<body data-screen="${s.id}"${app ? ' data-layout="app"' : ''}>
<main${app ? '' : ' class="auth"'}></main>
<script src="../../assets/registry.js"></script>
<script src="../../assets/shell.js"></script>
<script src="../../assets/chrome.js"></script>
<script src="../../assets/mtr-data.js"></script>
<script src="../../assets/mtr-core.js"></script>
${MODULES.map(m => `<script src="../../assets/${m}.js"></script>`).join('\n')}
<script src="../../assets/charts.js"></script>
<script src="../../assets/mtr-boot.js"></script>
</body>
</html>
`;
    const f = path.join(root, s.file);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, html);
    n++;
  });
});
const dir = (name, attrs) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Amazon Operations Portal — Screen Directory</title>
<link rel="stylesheet" href="${name === 'index' ? '' : '../'}assets/fonts.css">
<link rel="stylesheet" href="${name === 'index' ? '' : '../'}assets/styles.css">
<link rel="stylesheet" href="${name === 'index' ? '' : '../'}assets/mtr.css">
</head>
<body ${attrs}>
<div id="app"></div>
<script src="${name === 'index' ? '' : '../'}assets/registry.js"></script>
<script src="${name === 'index' ? '' : '../'}assets/directory.js"></script>
</body>
</html>
`;
fs.writeFileSync(path.join(root, 'index.html'), dir('index', 'data-page="index"'));
fs.mkdirSync(path.join(root, 'directory'), { recursive: true });
P.portals.forEach(p => fs.writeFileSync(path.join(root, 'directory', p.id + '.html'), dir(p.id, `data-page="portal" data-portal="${p.id}"`)));
console.log('wrote ' + n + ' screens, index.html and ' + P.portals.length + ' directory pages');
